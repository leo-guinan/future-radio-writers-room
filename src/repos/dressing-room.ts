// A dressing room is one character's own repository: who they are, everything they've
// done in the room, and what they've learned. Every run lands here as a commit.
//
//   CHARACTER.md          persona — the character's voice and job (edit here, not in code)
//   history/YYYY-MM-DD/   one Markdown file per run, with provenance frontmatter
//   history.jsonl         index of every run (one line each)
//   memory/notes.md       durable notes: what worked, decisions, recurring conflicts
//   voice/voice.json      production voice settings (e.g. ElevenLabs voice name)
//   SHOW_BIBLE.md         the shared world, so the room can be loaded on its own
//   bible/                the character bible (generated by future-radio-character-bible)
//   memory/viewer-notes/  notes viewers proposed by pull request and the producer merged
//   CONTRIBUTING.md, .github/   how viewers propose changes, and the CI that checks them

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname } from "node:path";
import { join } from "node:path";
import type { AgentRun } from "../core/types.ts";
import { build as buildBible, initGithub, render as renderBible, type BibleModel } from "future-radio-character-bible";
import { Repo, REPOS_DIR, SubRepo } from "./git.ts";
import { ensureLicense } from "./license.ts";

const TEMPLATE_DIR = () => process.env.CHARACTERS_DIR ?? join(process.cwd(), "characters");
export const biblePackage = () =>
  process.env.CHARACTER_BIBLE_PACKAGE ?? `github:${process.env.GITHUB_OWNER ?? "OWNER"}/${process.env.REPO_PREFIX ?? "future-radio-"}character-bible`;

export interface HistoryEntry {
  runId: string;
  at: string;
  ideaId?: string;
  episodeId?: string;
  askedBy: string;
  eventId: string;
  eventHash: string;
  file: string;
  text: string;
}

const tokens = (s: string) => new Set(s.toLowerCase().match(/[a-z0-9]{4,}/g) ?? []);

/**
 * A character's home: their own repo (a dressing room) or, for an extra, their folder in
 * the shared extras repo. Everything below works the same way in both.
 */
export class DressingRoom {
  readonly repo: Repo;
  constructor(readonly character: string, home?: Repo) {
    this.repo = home ?? new Repo(`dressing-room-${character}`);
  }

  /** Extras live in a folder of the shared extras repo, not in a repo of their own. */
  get isExtra() {
    return this.repo instanceof SubRepo;
  }

  /** Open the room the first time, seeded from the template persona in characters/. */
  ensure(): this {
    if (this.repo.exists && this.repo.has("CHARACTER.md")) {
      if (!this.repo.has("bible/BIBLE.md")) this.refresh("Add the character bible and viewer contribution guide");
      return this;
    }
    if (this.isExtra) throw new Error(`No extra called ${this.character}. Open one with: npm run room -- extras open ${this.character}`);
    if (this.cloneFromGithub()) return this;
    this.repo.init();
    const template = join(TEMPLATE_DIR(), `${this.character}.md`);
    const persona = existsSync(template) ? readFileSync(template, "utf8") : `# ${this.character}\n`;
    const name = this.character[0].toUpperCase() + this.character.slice(1);
    this.repo.write("CHARACTER.md", persona);
    this.repo.write(
      "README.md",
      `# ${name}'s dressing room\n\nEverything ${name} has done in the Future Radio writers' room.\n\n` +
        `- \`CHARACTER.md\` — who ${name} is and what ${name} does. The room reads this on every run.\n` +
        `- \`history/\` — one file per run, newest last. Each carries the room event id and hash it came from.\n` +
        `- \`memory/notes.md\` — durable notes worth carrying into future episodes.\n` +
        `- \`voice/voice.json\` — production voice settings.\n\n` +
        `Episode repos never edit this repo. They project from it, pinned to a commit.\n`,
    );
    ensureLicense(this.repo);
    this.repo.write("history.jsonl", "");
    this.repo.write("memory/notes.md", `# ${name}'s notes\n\n`);
    this.repo.write("voice/voice.json", JSON.stringify({ character: this.character, provider: null, voice: null }, null, 2) + "\n");
    this.syncShowBible();
    initGithub(this.repo.dir, { pkg: biblePackage() });
    this.commitWithBible(`Open ${name}'s dressing room`);
    return this;
  }

  /**
   * On a fresh deploy the dressing room already exists on GitHub (with its history and
   * merged viewer notes): clone it rather than opening a new, empty one.
   */
  private cloneFromGithub(): boolean {
    const owner = process.env.GITHUB_OWNER;
    if (!owner || process.env.CLONE_DRESSING_ROOMS === "0" || existsSync(this.repo.dir)) return false;
    const url = `https://github.com/${owner}/${process.env.REPO_PREFIX ?? "future-radio-"}${this.repo.name}`;
    try {
      mkdirSync(dirname(this.repo.dir), { recursive: true });
      execFileSync("git", ["clone", "-q", url, this.repo.dir], { stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, GIT_TERMINAL_PROMPT: "0" } });
      return this.repo.has("CHARACTER.md");
    } catch {
      return false;
    }
  }

  /** Commit, then rebuild the bible so its changelog includes this commit, and fold that in. */
  commitWithBible(message: string): string {
    buildBible(this.repo.dir);
    this.repo.commit(message);
    return buildBible(this.repo.dir).changed.length ? this.repo.amend() : this.repo.head();
  }

  /** Copy the shared show bible in, so the dressing room loads on its own. */
  private syncShowBible() {
    const src = join(TEMPLATE_DIR(), "show-bible.md");
    if (!existsSync(src)) return;
    const text = readFileSync(src, "utf8");
    if (!this.repo.has("SHOW_BIBLE.md") || this.repo.read("SHOW_BIBLE.md") !== text) this.repo.write("SHOW_BIBLE.md", text);
  }

  /** Bring scaffolding, show bible and character bible up to date, and commit if anything changed. */
  refresh(message = "Rebuild the character bible"): string {
    if (!this.isExtra) {
      // An extra shares the extras repo's show bible and contribution guide.
      this.syncShowBible();
      initGithub(this.repo.dir, { pkg: biblePackage() });
    }
    return this.commitWithBible(message);
  }

  /** Point the CI workflow and contribution guide at the published character-bible package. */
  retarget(pkg: string): string {
    if (this.isExtra) return this.repo.head();
    initGithub(this.repo.dir, { pkg, force: true });
    return this.commitWithBible(`Use ${pkg} for the character bible`);
  }

  bible(): BibleModel {
    this.ensure();
    return renderBible(this.repo.dir).model;
  }

  /** Canon the room should carry into every run: the producer's notes and merged viewer notes. */
  canon(): string {
    const m = this.bible();
    const lines = [...m.canon.notes.map((n) => `- ${n}`), ...m.canon.viewerNotes.map((v) => `- ${v.note.split("\n")[0]} (from ${v.from}, a viewer)`)];
    return lines.length ? `## Canon you carry\n\n${lines.join("\n")}` : "";
  }

  persona(): string {
    return this.ensure().repo.read("CHARACTER.md");
  }

  /** Record one run. Returns the commit sha and the file written. */
  recordRun(run: AgentRun, at: string, eventId: string, eventHash: string): { sha: string; file: string } {
    this.ensure();
    const day = at.slice(0, 10);
    const file = `history/${day}/${run.runId}.md`;
    const front = [
      "---",
      `run: ${run.runId}`,
      `character: ${run.character}`,
      `at: ${at}`,
      `asked_by: ${JSON.stringify(run.askedBy)}`,
      run.ideaId ? `idea: ${run.ideaId}` : null,
      run.episodeId ? `episode: ${run.episodeId}` : null,
      `room_event: ${eventId}`,
      `room_event_hash: ${eventHash}`,
      `model: ${run.model}`,
      `usage: { input: ${run.usage.input}, output: ${run.usage.output} }`,
      `cost_usd: ${run.costUsd === null ? "unknown" : run.costUsd}`,
      run.citations?.length ? `citations: [${run.citations.join(", ")}]` : null,
      run.flags?.length ? `flags: ${JSON.stringify(run.flags)}` : null,
      "---",
    ]
      .filter(Boolean)
      .join("\n");
    const body = `${front}\n\n${run.prompt ? `> ${run.prompt.replace(/\n/g, "\n> ")}\n\n` : ""}${run.text}\n\n<details><summary>structured output</summary>\n\n\`\`\`json\n${JSON.stringify(run.output, null, 2)}\n\`\`\`\n\n</details>\n`;
    this.repo.write(file, body);
    const entry: HistoryEntry = {
      runId: run.runId,
      at,
      ideaId: run.ideaId,
      episodeId: run.episodeId,
      askedBy: run.askedBy,
      eventId,
      eventHash,
      file,
      text: run.text.slice(0, 600),
    };
    this.repo.append("history.jsonl", JSON.stringify(entry) + "\n");
    buildBible(this.repo.dir);
    const sha = this.repo.commit(`${run.character}: ${run.runId}${run.ideaId ? ` on ${run.ideaId}` : ""}${run.episodeId ? ` (${run.episodeId})` : ""}`);
    return { sha, file };
  }

  /** Record the production voice. */
  setVoice(voice: { provider: string; name: string; id: string; kind?: string; direction?: string }): string {
    this.ensure();
    const next = JSON.stringify({ character: this.character, ...voice }, null, 2) + "\n";
    if (this.repo.read("voice/voice.json") === next) return this.repo.head();
    this.repo.write("voice/voice.json", next);
    return this.commitWithBible(`${this.character}: voice is ${voice.name}`);
  }

  /** A note that is already in memory is not written twice. */
  hasNote(note: string): boolean {
    return this.notes().some((l) => l.includes(note));
  }

  /**
   * A released episode is the strongest record of how a character sounds. Their lines
   * from it go into history as an appearance, pinned to the release's checksum.
   */
  recordAppearance(a: { episodeId: string; version: string; title: string; lines: string[]; kind?: "lines" | "cues"; releaseSha256: string; at: string; eventId: string; eventHash: string; script: string }): { sha: string; file: string; created: boolean } {
    const what = a.kind === "cues" ? `${a.lines.length} cue${a.lines.length === 1 ? "" : "s"}, no spoken lines` : `${a.lines.length} line${a.lines.length === 1 ? "" : "s"}`;
    this.ensure();
    const runId = `${a.episodeId}-${a.version}`;
    const file = `history/appearances/${runId}.md`;
    if (this.history().some((h) => h.runId === runId)) return { sha: this.repo.head(), file, created: false };
    const body = [
      "---",
      `run: ${runId}`,
      `character: ${this.character}`,
      `at: ${a.at}`,
      `asked_by: "released"`,
      `episode: ${a.episodeId}`,
      `release: ${a.version}`,
      `release_sha256: ${a.releaseSha256}`,
      `room_event: ${a.eventId}`,
      `room_event_hash: ${a.eventHash}`,
      `model: released`,
      `script: ${JSON.stringify(a.script)}`,
      "---",
      "",
      `# ${a.episodeId} — ${a.title} (${a.version}, as released)`,
      "",
      `${what}.`,
      "",
      ...a.lines.map((l) => `- ${l}`),
      "",
    ].join("\n");
    this.repo.write(file, body);
    const entry: HistoryEntry = { runId, at: a.at, episodeId: a.episodeId, askedBy: "released", eventId: a.eventId, eventHash: a.eventHash, file, text: a.lines.join(" ").slice(0, 600) };
    this.repo.append("history.jsonl", JSON.stringify(entry) + "\n");
    return { sha: this.commitWithBible(`${this.character}: appears in ${a.episodeId} ${a.version} (${what})`), file, created: true };
  }

  remember(note: string, source: string): string {
    this.ensure();
    this.repo.append("memory/notes.md", `- ${new Date().toISOString().slice(0, 10)} — ${note} _(source: ${source})_\n`);
    return this.commitWithBible(`${this.character}: remember — ${note.slice(0, 60)}`);
  }

  history(): HistoryEntry[] {
    this.ensure();
    return this.repo
      .read("history.jsonl")
      .split("\n")
      .filter(Boolean)
      .map((l) => JSON.parse(l) as HistoryEntry);
  }

  notes(): string[] {
    this.ensure();
    return this.repo
      .read("memory/notes.md")
      .split("\n")
      .filter((l) => l.startsWith("- "));
  }

  /** History entries most relevant to a query (token overlap, newest wins ties). */
  relevant(query: string, k = 5, ideaId?: string): HistoryEntry[] {
    const q = tokens(query);
    return this.history()
      .map((h, i) => {
        const t = tokens(h.text);
        let score = 0;
        for (const w of q) if (t.has(w)) score++;
        if (ideaId && h.ideaId === ideaId) score += 5;
        return { h, score, i };
      })
      .filter((x) => x.score > 0)
      .sort((a, b) => b.score - a.score || b.i - a.i)
      .slice(0, k)
      .map((x) => x.h);
  }
}

const rooms = new Map<string, DressingRoom>();
export const dressingRoom = (c: string) => {
  const key = `${REPOS_DIR()}|${c}`;
  let r = rooms.get(key);
  if (!r) rooms.set(key, (r = new DressingRoom(c)));
  return r;
};

export const reposEnabled = () => process.env.REPOS_DISABLED !== "1";
